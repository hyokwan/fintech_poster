const Help = {
  open() {
    const h = HELP[location.pathname];
    if (!h) return;
    let dlg = document.getElementById('helpDlg');
    if (!dlg) {
      dlg = document.createElement('dialog');
      dlg.id = 'helpDlg';
      dlg.className = 'help-dlg';
      document.body.append(dlg);
      dlg.addEventListener('click', (e) => { if (e.target === dlg) dlg.close(); }); // 바깥 누르면 닫기
    }
    dlg.innerHTML = `
      <div class="help-head"><div><small>사용법</small><h2>${h.title}</h2></div><button class="help-x" title="닫기">×</button></div>
      <p class="help-intro">${h.intro}</p>
      <ol class="help-steps">${h.steps.map((s) => `<li>${s}</li>`).join('')}</ol>
      ${h.tips.length ? `<div class="help-tips"><b>💡 알아두면 좋아요</b><ul>${h.tips.map((t) => `<li>${t}</li>`).join('')}</ul></div>` : ''}
      <div class="help-foot"><button class="btn primary">알겠어요</button></div>`;
    dlg.querySelector('.help-x').onclick = () => dlg.close();
    dlg.querySelector('.help-foot .btn').onclick = () => dlg.close();
    dlg.showModal();
  },
  // 이 메뉴를 처음 열었으면 한 번 보여줌
  firstVisit() {
    const key = 'help-seen:' + location.pathname;
    try {
      if (localStorage.getItem(key)) return;
      localStorage.setItem(key, '1');
    } catch (e) { return; }
    if (HELP[location.pathname]) setTimeout(Help.open, 400);
  },
};
